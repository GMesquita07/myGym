CREATE TABLE workout_plans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  description VARCHAR(500) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE plan_exercises (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_id BIGINT NOT NULL REFERENCES workout_plans(id) ON DELETE CASCADE,
  position INT NOT NULL CHECK (position >= 0),
  name VARCHAR(120) NOT NULL,
  target_sets INT NOT NULL CHECK (target_sets BETWEEN 1 AND 20),
  target_reps INT NOT NULL CHECK (target_reps BETWEEN 1 AND 100),
  rest_seconds INT NOT NULL CHECK (rest_seconds BETWEEN 0 AND 600),
  UNIQUE (plan_id, position)
);

CREATE TABLE workout_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_id BIGINT REFERENCES workout_plans(id) ON DELETE SET NULL,
  plan_name VARCHAR(100) NOT NULL,
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ,
  notes VARCHAR(1000) NOT NULL DEFAULT ''
);

CREATE TABLE session_exercises (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL REFERENCES workout_sessions(id) ON DELETE CASCADE,
  source_exercise_id BIGINT REFERENCES plan_exercises(id) ON DELETE SET NULL,
  position INT NOT NULL,
  name VARCHAR(120) NOT NULL,
  target_sets INT NOT NULL,
  target_reps INT NOT NULL,
  rest_seconds INT NOT NULL,
  UNIQUE (session_id, position)
);

CREATE TABLE performed_sets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_exercise_id BIGINT NOT NULL REFERENCES session_exercises(id) ON DELETE CASCADE,
  set_number INT NOT NULL CHECK (set_number > 0),
  kind VARCHAR(10) NOT NULL CHECK (kind IN ('WARMUP', 'WORK')),
  weight_kg NUMERIC(7,2) NOT NULL CHECK (weight_kg >= 0 AND weight_kg <= 2000),
  reps INT NOT NULL CHECK (reps BETWEEN 1 AND 100),
  rpe NUMERIC(3,1) CHECK (rpe BETWEEN 1 AND 10),
  completed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (session_exercise_id, set_number)
);

CREATE INDEX idx_sessions_started ON workout_sessions(started_at DESC);
CREATE INDEX idx_sets_exercise ON session_exercises(source_exercise_id, session_id);
